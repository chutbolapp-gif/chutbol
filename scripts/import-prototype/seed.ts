export function readDataset(dir: string): Dataset {
  const read = <T>(kind: string): T[] => {
    const d = join(dir, kind);
    return existsSync(d) ? readdirSync(d).filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(readFileSync(join(d, f), 'utf8')) as T) : [];
  };
  return { leagues: read('leagues'), rounds: read('rounds'), ratings: read('ratings') };
}

// ---------- SQL ----------
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
function lit(v: unknown, type?: string): string {
  if (v === null || v === undefined) return 'null';
  if (type === 'jsonb') return `${q(JSON.stringify(v))}::jsonb`;
  if (type === 'text[]') return (v as string[]).length ? `array[${(v as string[]).map(q).join(', ')}]` : `'{}'::text[]`;
  if (type === 'timestamptz') return `${q(String(v))}::timestamptz`;
  if (typeof v === 'number') { if (!Number.isFinite(v)) throw new Error(`bad number ${v}`); return String(v); }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return q(v);
  throw new Error(`cannot write ${JSON.stringify(v)} without a type`);
}

type Cols = Record<string, string | undefined>;
function insert(table: string, cols: Cols, list: object[]): string {
  if (!list.length) return `-- ${table}: none\n`;
  const names = Object.keys(cols);
  const values = list.map(row => `  (${names.map(n => lit((row as Record<string, unknown>)[n], cols[n])).join(', ')})`);
  return `insert into public.${table} (${names.join(', ')}) values\n${values.join(',\n')};\n`;
}

