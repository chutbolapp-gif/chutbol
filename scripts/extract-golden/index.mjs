#!/usr/bin/env node
// Produces the "right answers" for the scoring port by running the prototype's own,
// unchanged functions on the exported league data.
//
//   pnpm golden          regenerate packages/scoring/golden + docs/scoring-deps.md
//   pnpm golden:check    regenerate in memory and fail if anything on disk differs
//   pnpm deps            only rewrite docs/scoring-deps.md
//
// Policy (decided by the owner, 2026-10-18): the CURRENT formula is the truth. Ratings
// stored in the round files were produced by an older formula, so before computing
// anything that reads stored ratings (roundScores, playerOVR ...) every round is
// "re-saved" exactly the way the prototype does it on save (updateRatings).
// The differences are written to golden/stored-vs-current.json.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPrototype, SCORING_ROOTS, TOOL_ROOTS } from './prototype.mjs';
import { createSandbox } from './sandbox.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const PROTO = join(ROOT, 'docs/prototype/soccerfriends.html');
const DATA = join(ROOT, 'docs/prototype/data');
const GOLDEN = join(ROOT, 'packages/scoring/golden');
const DEPS_DOC = join(ROOT, 'docs/scoring-deps.md');
const FIXTURES = join(ROOT, 'packages/scoring/fixtures'); // synthetic edge cases (step 4)

const args = new Set(process.argv.slice(2));
const sha = buf => createHash('sha256').update(buf).digest('hex').slice(0, 16);

// ---------- stable JSON ----------
function normalize(v) {
  const tag = Object.prototype.toString.call(v);
  if (tag === '[object Set]') return [...v].map(normalize);
  if (tag === '[object Map]') return normalize(Object.fromEntries(v));
  if (Array.isArray(v)) return v.map(normalize);
  if (v && typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort()) if (v[k] !== undefined) out[k] = normalize(v[k]);
    return out;
  }
  if (typeof v === 'number' && !Number.isFinite(v)) return { $number: String(v) };
  return v;
}
const stable = v => JSON.stringify(normalize(v), null, 1) + '\n';

// ---------- data ----------
function readDataset(dir) {
  const files = {};
  const sets = { leagues: [], rounds: [], ratings: [] };
  for (const kind of Object.keys(sets)) {
    const d = join(dir, kind);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d).filter(f => f.endsWith('.json')).sort()) {
      const raw = readFileSync(join(d, f), 'utf8');
      files[relative(ROOT, join(d, f)).replaceAll('\\', '/')] = sha(raw);
      sets[kind].push(raw);
    }
  }
  return { files, sets };
}

// ---------- dependency doc ----------
function depsDoc(proto, names) {
  const rows = names.map(n => {
    const s = proto.symbols.get(n);
    const d = [...proto.deps.get(n)].sort();
    const f = proto.flagsOf(n);
    const tool = TOOL_ROOTS.includes(n) && !names.filter(x => !TOOL_ROOTS.includes(x)).some(x => proto.deps.get(x).has(n));
    return `| ${s.line} | \`${n}\` | ${s.kind} | ${d.map(x => `\`${x}\``).join(', ') || '—'} | ${[...(tool ? ['extractor only, not ported'] : []), ...f].join('; ') || ''} |`;
  });
  return `# Scoring dependency map

> Generated by \`pnpm deps\` from docs/prototype/soccerfriends.html (sha ${sha(proto.html)}). Do not edit by hand.

Roots: ${SCORING_ROOTS.map(x => `\`${x}\``).join(', ')}. Closure: **${names.filter(n => !TOOL_ROOTS.includes(n)).length} symbols** (scope-aware: a local variable that shares a name with a global is not a dependency).

| Line | Symbol | Kind | Depends on | Flags |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

## What the port must change

- \`S.rounds\` (leagueRounds) and \`S.ratings\` (rdoc) become explicit inputs.
- \`S.admin\` (playerOVR) becomes an explicit \`isAdmin\` argument.
- \`OVRC\` is a module-level cache keyed by player+role only (no league, no admin flag). The port has no global cache.
- playerOVR returns whole round objects inside \`hist\`; the port returns round ids.
- \`GF\`, \`GKS\`, \`LP\`, \`TD\` are local variables inside rateMatch/playerOVR, not global constants.
`;
}

// ---------- golden generation ----------
function generate(proto) {
  const scoringNames = proto.closure(SCORING_ROOTS);
  const allNames = proto.closure([...SCORING_ROOTS, ...TOOL_ROOTS]);
  const source = proto.extract(allNames);
  const out = new Map(); // relative path -> content

  const runDataset = (label, dir, prefix) => {
    const { files, sets } = readDataset(dir);
    const api = createSandbox(source, [...SCORING_ROOTS, ...TOOL_ROOTS, 'leagueRounds']);
    const S = api.S;
    S.admin = true;
    sets.leagues.forEach(j => { const l = api.parse(j); S.leagues[l.id] = l; });
    sets.rounds.forEach(j => { const r = api.parse(j); S.rounds[r.id] = r; });
    sets.ratings.forEach(j => { const d = api.parse(j); S.ratings[d.id] = d; });
    const rounds = Object.values(S.rounds).sort((a, b) => a.created - b.created || (a.id < b.id ? -1 : 1));
    const playable = m => m.status === 'done' && m.lu;

    // 1. stored ratings vs. current formula (before re-saving)
    const report = { policy: 'current-formula', rounds: {} };
    for (const r of rounds) {
      const rows = [];
      for (const m of r.matches) {
        if (!playable(m)) continue;
        api.resetCache();
        const x = api.rateMatch(r, m);
        const pids = [...new Set([...Object.keys(x.ratings), ...Object.keys(m.ratings || {})])].sort();
        for (const p of pids) {
          const stored = (m.ratings || {})[p];
          const current = x.ratings[p];
          if (stored !== current) rows.push({ match: m.id, n: m.n, player: p, stored: stored ?? null, current: current ?? null, parts: x.parts[p] ?? null });
        }
      }
      const total = r.matches.filter(playable).reduce((s, m) => s + new Set([...Object.keys(m.ratings || {})]).size, 0);
      if (total || rows.length) report.rounds[r.id] = { storedRatings: total, mismatches: rows.length, rows };
    }
    out.set(`${prefix}stored-vs-current.json`, stable(report));

    // 2. re-save every round, as the prototype does on save (admin only)
    for (const r of rounds) { api.resetCache(); api.updateRatings(r); }

    // 3. per-round outputs
    for (const r of rounds) {
      const rm = {};
      for (const m of r.matches) {
        if (!playable(m)) continue;
        api.resetCache();
        rm[m.id] = { n: m.n, ...api.rateMatch(r, m) };
      }
      const base = { roundId: r.id, leagueId: r.leagueId, status: r.status, voided: !!r.voided };
      if (Object.keys(rm).length) out.set(`${prefix}rateMatch/${r.id}.json`, stable({ ...base, matches: rm }));

      api.resetCache();
      out.set(`${prefix}teamDay/${r.id}.json`, stable({ ...base, teamDay: api.teamDay(r) }));

      const rs = {};
      for (const kind of ['field', 'gk', null]) { api.resetCache(); rs[kind ?? 'all'] = api.roundScores(r, kind ?? undefined); }
      out.set(`${prefix}roundScores/${r.id}.json`, stable({ ...base, ...rs }));

      const gk = {};
      for (const t of r.teams || []) {
        api.resetCache();
        gk[t.id] = { counts: api.gkCounts(r, t.id), auto: api.autoGk(r, t.id) };
      }
      out.set(`${prefix}gk/${r.id}.json`, stable({ ...base, gkOrder: r.gkOrder ?? null, nextPair: r.nextPair ?? null, nextGk: r.nextGk ?? null, teams: gk }));
    }

    // 4. playerOVR for every player and role, as admin and as a member
    for (const l of Object.values(S.leagues).sort((a, b) => (a.id < b.id ? -1 : 1))) {
      const pids = [...new Set([
        ...(l.players || []).map(p => p.id),
        ...api.leagueRounds(l.id).flatMap(r => (r.teams || []).flatMap(t => t.players)),
      ])].sort();
      const res = { leagueId: l.id, players: {} };
      for (const admin of [true, false]) {
        S.admin = admin;
        for (const pid of pids) for (const role of ['f', 'g']) {
          api.resetCache();
          const v = api.playerOVR(l, pid, role);
          const vv = v && { ...v, hist: v.hist.map(h => ({ ...h, r: h.r.id })) };
          ((res.players[pid] ??= {})[role] ??= {})[admin ? 'admin' : 'member'] = vv;
        }
      }
      S.admin = true;
      out.set(`${prefix}playerOVR/${l.id}.json`, stable(res));
    }
    return files;
  };

  const realFiles = runDataset('real', DATA, '');
  const fixtureFiles = {};
  if (existsSync(FIXTURES)) {
    for (const name of readdirSync(FIXTURES).sort()) {
      Object.assign(fixtureFiles, runDataset(name, join(FIXTURES, name), `fixtures/${name}/`));
    }
  }

  out.set('_meta.json', stable({
    note: 'Generated by scripts/extract-golden. Do not edit by hand. Regenerate with `pnpm golden`.',
    policy: 'current-formula: stored match ratings are recomputed (prototype updateRatings) before roundScores/playerOVR',
    prototype: { file: 'docs/prototype/soccerfriends.html', sha: sha(proto.html) },
    inputs: { ...realFiles, ...fixtureFiles },
    symbols: scoringNames,
  }));
  return { out, names: allNames };
}

// ---------- main ----------
const proto = loadPrototype(PROTO);
const doc = depsDoc(proto, proto.closure([...SCORING_ROOTS, ...TOOL_ROOTS]));

if (args.has('--deps-only')) {
  writeFileSync(DEPS_DOC, doc);
  console.log(`wrote ${relative(ROOT, DEPS_DOC)}`);
  process.exit(0);
}

const a = generate(proto);
const b = generate(loadPrototype(PROTO)); // fresh parse + fresh sandbox
const nondet = [...a.out.keys()].filter(k => a.out.get(k) !== b.out.get(k));
if (nondet.length) {
  console.error('NON-DETERMINISTIC output (two runs differ):\n  ' + nondet.join('\n  '));
  process.exit(1);
}

const listDisk = dir => existsSync(dir) ? readdirSync(dir, { recursive: true, withFileTypes: true })
  .filter(e => e.isFile()).map(e => relative(GOLDEN, join(e.parentPath ?? e.path, e.name)).replaceAll('\\', '/')) : [];

if (args.has('--check')) {
  const disk = new Set(listDisk(GOLDEN));
  const problems = [];
  for (const [k, v] of a.out) {
    if (!disk.has(k)) problems.push(`missing  ${k}`);
    else if (readFileSync(join(GOLDEN, k), 'utf8') !== v) problems.push(`changed  ${k}`);
    disk.delete(k);
  }
  disk.forEach(k => problems.push(`extra    ${k}`));
  if (existsSync(DEPS_DOC) && readFileSync(DEPS_DOC, 'utf8') !== doc) problems.push('changed  docs/scoring-deps.md');
  if (problems.length) { console.error('golden is out of date:\n  ' + problems.join('\n  ') + '\nRun `pnpm golden`.'); process.exit(1); }
  console.log(`golden is up to date (${a.out.size} files, deterministic)`);
  process.exit(0);
}

rmSync(GOLDEN, { recursive: true, force: true });
for (const [k, v] of a.out) {
  const p = join(GOLDEN, k);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, v);
}
writeFileSync(DEPS_DOC, doc);

const rep = JSON.parse(a.out.get('stored-vs-current.json'));
console.log(`wrote ${a.out.size} golden files to ${relative(ROOT, GOLDEN)} (deterministic: 2 runs identical)`);
for (const [rid, x] of Object.entries(rep.rounds)) console.log(`  round ${rid}: ${x.mismatches} of ${x.storedRatings} stored ratings differ from the current formula`);
